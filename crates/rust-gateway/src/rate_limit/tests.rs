/// ip.helper.spec.ts, index.spec.ts: RL-07, RL-08.
#[test]
fn rl_07_ip_helper_spec() {
    let n = |ip: &str| normalize_ip(ip, DEFAULT_IPV6_SUBNET);
    // returns IPv4 addresses unchanged
    assert_eq!(n("203.0.113.7"), "203.0.113.7");
    // strips the IPv4-mapped prefix
    for input in [
        "::ffff:203.0.113.7",
        "::FFFF:203.0.113.7",
        "::ffff:cb00:7107",
        "0:0:0:0:0:ffff:203.0.113.7",
    ] {
        assert_eq!(n(input), "203.0.113.7", "{input}");
    }
    // masks IPv6 addresses to their /64 prefix by default
    assert_eq!(
        n("2001:db8:1:2:aaaa:bbbb:cccc:dddd"),
        "2001:db8:1:2:0:0:0:0/64"
    );
    assert_eq!(n("2001:db8:1:2::1"), "2001:db8:1:2:0:0:0:0/64");
    // same /64 shares a key, different /64 does not
    assert_eq!(
        n("2001:db8:1:2::1"),
        n("2001:0DB8:0001:0002:ffff:ffff:ffff:fffe")
    );
    assert_ne!(n("2001:db8:1:2::1"), n("2001:db8:1:3::1"));
    // honours a custom subnet, including one that is not a multiple of 16
    assert_eq!(
        normalize_ip("2001:db8:1:2ff::1", 56),
        "2001:db8:1:200:0:0:0:0/56"
    );
    assert_eq!(
        normalize_ip("2001:db8:1:2::1", 48),
        "2001:db8:1:0:0:0:0:0/48"
    );
    assert_eq!(
        normalize_ip("2001:db8:1:2::1", 128),
        "2001:db8:1:2:0:0:0:1/128"
    );
    // compressed forms, unspecified and loopback
    assert_eq!(n("::1"), "0:0:0:0:0:0:0:0/64");
    assert_eq!(normalize_ip("::1", 128), "0:0:0:0:0:0:0:1/128");
    assert_eq!(n("fe80::"), "fe80:0:0:0:0:0:0:0/64");
    // embedded IPv4 tail that is not IPv4-mapped
    assert_eq!(
        normalize_ip("64:ff9b::203.0.113.7", 128),
        "64:ff9b:0:0:0:0:cb00:7107/128"
    );
    // drops the zone index
    assert_eq!(n("fe80::1%eth0"), "fe80:0:0:0:0:0:0:0/64");
    // returns non-IP values unchanged
    assert_eq!(n("unknown"), "unknown");
    assert_eq!(n(""), "");

    // index.spec.ts
    assert_eq!(DEFAULT_IPV6_SUBNET, 64);
    assert_eq!(n("::ffff:127.0.0.1"), "127.0.0.1");
    assert_eq!(n("2001:db8:1:2::abcd"), "2001:db8:1:2:0:0:0:0/64");
    assert_eq!(
        normalize_ip("2001:db8:1:2::abcd", 128),
        "2001:db8:1:2:0:0:0:abcd/128"
    );
}

