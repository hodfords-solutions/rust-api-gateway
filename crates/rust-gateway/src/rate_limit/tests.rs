/// CFG-06, CFG-07: invalid options fail construction with the reference's messages.
#[test]
fn cfg_06_option_validation() {
    let with = |f: &dyn Fn(&mut RateLimitOptions)| {
        let mut opts = options(true);
        f(&mut opts);
        RateLimiter::new(&opts, &RedisOptions::new("127.0.0.1", 6379))
            .map(|_| ())
            .map_err(|e| e.to_string())
    };
    let cases: [(OptionsChange<'_>, &str); 6] = [
        (&|o| o.anonymous_ip_limit = Some(10), "set together"),
        (&|o| o.anonymous_ip_ttl = Some(60.0), "set together"),
        (
            &|o| {
                o.anonymous_ip_limit = Some(0);
                o.anonymous_ip_ttl = Some(60.0);
            },
            "positive numbers",
        ),
        (
            &|o| {
                o.anonymous_ip_limit = Some(1);
                o.anonymous_ip_ttl = Some(0.0);
            },
            "positive numbers",
        ),
        (
            &|o| {
                o.anonymous_ip_limit = Some(1);
                o.anonymous_ip_ttl = Some(f64::INFINITY);
            },
            "positive numbers",
        ),
        (&|o| o.ipv6_subnet = Some(0), "ipv6Subnet"),
    ];
    for (change, message) in cases {
        let error = with(change).expect_err("invalid");
        assert!(error.contains(message), "{error}");
    }
    assert!(
        with(&|o| {
            o.anonymous_ip_limit = Some(1);
            o.anonymous_ip_ttl = Some(0.5);
        })
        .is_ok()
    );
    // Validation applies when disabled too, as in the reference's constructor.
    assert!(
        with(&|o| {
            o.enabled = false;
            o.ipv6_subnet = Some(200);
        })
        .is_err()
    );
    // A trust proxy entry that does not compile.
    assert_eq!(
        with(&|o| o.trust_proxy = TrustProxy::from_comma_separated("loopback, foo")),
        Err("invalid IP address: foo".to_owned())
    );
}

