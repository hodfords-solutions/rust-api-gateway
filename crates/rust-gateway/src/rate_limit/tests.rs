const HIGH: u64 = 1_000_000;
const ROUTE: RouteKey<'static> = RouteKey {
    service: "svc",
    method: "GET",
    pattern: "/things",
};

fn ip(text: &str) -> IpAddr {
    text.parse().expect("IP address")
}

fn options(enabled: bool) -> RateLimitOptions {
    RateLimitOptions::new(
        enabled,
        BucketLimit::new(HIGH, 60.0),
        BucketLimit::new(HIGH, 60.0),
    )
}

fn limiter(options: RateLimitOptions, store: MemoryStore) -> RateLimiter {
    RateLimiter::in_memory(&options, store).expect("valid options")
}

fn state_for(limiter: &RateLimiter, address: &str) -> RateLimitState {
    limiter.request_state(Some(ip(address)), &HeaderMap::new())
}

/// The reference's `checkLimitOfRequest`: Global IP (if not yet counted), then the rest.
async fn check(
    limiter: &RateLimiter,
    state: &mut RateLimitState,
    identity: Option<Identity>,
    limits: &[RouteLimit],
) -> Result<(), RateLimitError> {
    limiter.count_global_ip(state).await?;
    limiter.check_limits(state, identity, ROUTE, limits).await
}

type Resolver<'a> = &'a dyn Fn(&str) -> Option<Identity>;
type OptionsChange<'a> = &'a dyn Fn(&mut RateLimitOptions);

/// Runs `checkLimitOfRequest` for a fresh request from `address`, resolving the Identity
/// with `resolve` (given the normalised address), or the default Identity when `None`.
async fn request(
    limiter: &RateLimiter,
    address: &str,
    resolve: Option<Resolver<'_>>,
    limits: &[RouteLimit],
) -> (RateLimitState, Result<(), RateLimitError>) {
    let mut state = state_for(limiter, address);
    let identity = match resolve {
        Some(resolve) => resolve(state.client_key()),
        None => Some(state.default_identity()),
    };
    let result = check(limiter, &mut state, identity, limits).await;
    (state, result)
}

fn is_too_many(result: &Result<(), RateLimitError>) -> bool {
    matches!(result, Err(RateLimitError::TooManyRequests(_)))
}

fn route_bucket(identity: &str, limit: &RouteLimit) -> String {
    route_key(
        &ROUTE,
        identity,
        limit.limit,
        window_ms(limit.ttl),
        limit.status.filter(|&s| s != 0),
    )
}

fn status_limit(limit: u64, status: u16) -> RouteLimit {
    RouteLimit {
        limit,
        ttl: 60.0,
        status: Some(status),
    }
}

