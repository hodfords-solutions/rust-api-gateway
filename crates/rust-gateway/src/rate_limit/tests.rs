fn user_or_ip(user: Option<&str>) -> impl Fn(&str) -> Option<Identity> + '_ {
    move |ip: &str| match user {
        Some(id) => Some(Identity::authenticated(format!("user:{id}"))),
        None => Some(Identity::anonymous(format!("ip:{ip}"))),
    }
}

