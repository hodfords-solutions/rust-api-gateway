/// RL-14: same Identity shares a Custom Bucket; different Identities are independent.
#[tokio::test]
async fn rl_14_custom_bucket_per_identity() {
    let store = MemoryStore::default();
    let mut opts = options(true);
    opts.custom = BucketLimit::new(3, 60.0);
    let l = limiter(opts, store.clone());
    let user = |id: &'static str| move |_: &str| Some(Identity::anonymous(format!("user:{id}")));

    for _ in 0..3 {
        assert!(
            request(&l, "10.0.0.1", Some(&user("42")), &[])
                .await
                .1
                .is_ok()
        );
    }
    assert!(is_too_many(
        &request(&l, "10.0.0.1", Some(&user("42")), &[]).await.1
    ));
    assert!(
        request(&l, "10.0.0.1", Some(&user("99")), &[])
            .await
            .1
            .is_ok()
    );

    assert_eq!(store.get(&custom_key("user:42")), Some(3));
    assert_eq!(store.get(&custom_key("user:99")), Some(1));
    assert_eq!(store.get(&custom_key("ip:10.0.0.1")), None);
}

