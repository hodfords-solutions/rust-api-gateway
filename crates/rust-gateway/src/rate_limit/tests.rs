/// RL-07, RL-08: `normalize_ip` agrees with the reference's `normalizeIp` on every input.
#[test]
fn rl_07_normalize_ip_matches_golden_vectors() {
    let golden = golden();
    let cases = golden["normalize"].as_array().expect("normalize");
    let mut failures = Vec::new();
    for case in cases {
        let input = case["input"].as_str().expect("input");
        let subnet = case["subnet"]
            .as_u64()
            .map_or(DEFAULT_IPV6_SUBNET, |s| s as u32);
        let expected = case["output"].as_str().expect("output");
        let actual = normalize_ip(input, subnet);
        if actual != expected {
            failures.push(format!(
                "{input:?}/{subnet}: expected {expected:?}, got {actual:?}"
            ));
        }
    }
    assert!(failures.is_empty(), "{}", failures.join("\n"));
}

/// RL-06: `TrustedProxies::new` accepts and rejects exactly what Express and `proxy-addr`
/// accept and reject, with the same messages.
#[test]
fn rl_06_trust_proxy_compilation_matches_golden_vectors() {
    let golden = golden();
    let mut failures = Vec::new();
    for case in golden["trustCompiled"].as_array().expect("trustCompiled") {
        let trust = trust_from_json(&case["trust"]);
        let result = TrustedProxies::new(&trust);
        match (case["ok"].as_bool(), result) {
            (Some(true), Ok(_)) => {}
            (Some(false), Err(error)) => {
                if error.to_string() != case["error"].as_str().unwrap_or_default() {
                    failures.push(format!("{}: message {error}", case["trust"]));
                }
            }
            (_, result) => failures.push(format!("{}: got {result:?}", case["trust"])),
        }
    }
    assert!(failures.is_empty(), "{}", failures.join("\n"));
}

/// RL-06: the client address matches Express's `request.ip` for every trust setting, peer
/// address and `X-Forwarded-For` value in the vectors.
#[test]
fn rl_06_client_address_matches_golden_vectors() {
    let golden = golden();
    let peers: Vec<Option<IpAddr>> = golden["peers"]
        .as_array()
        .expect("peers")
        .iter()
        .map(|p| {
            p.as_str().map(|text| {
                let ip: IpAddr = text.parse().expect("peer address");
                assert_eq!(
                    ip.to_string(),
                    text,
                    "peer formats like Node's remoteAddress"
                );
                ip
            })
        })
        .collect();
    let forwarded: Vec<Option<&str>> = golden["forwardedFor"]
        .as_array()
        .expect("forwardedFor")
        .iter()
        .map(Value::as_str)
        .collect();
    let mut failures = Vec::new();
    let mut checked = 0;
    for table in golden["clientAddress"].as_array().expect("clientAddress") {
        let trust = TrustedProxies::new(&trust_from_json(&table["trust"])).expect("compiles");
        for (p, row) in table["ips"].as_array().expect("ips").iter().enumerate() {
            for (x, expected) in row.as_array().expect("row").iter().enumerate() {
                let actual = trust.client_address(peers[p], forwarded[x]);
                checked += 1;
                if actual.as_deref() != expected.as_str() {
                    failures.push(format!(
                        "trust {} peer {:?} xff {:?}: expected {expected}, got {actual:?}",
                        table["trust"], peers[p], forwarded[x]
                    ));
                }
            }
        }
    }
    assert!(checked > 10_000);
    assert!(
        failures.is_empty(),
        "{} of {checked} differ:\n{}",
        failures.len(),
        failures.join("\n")
    );
}

