const GOLDEN: &str = include_str!("testdata/golden.json");

fn golden() -> Value {
    serde_json::from_str(GOLDEN).expect("golden.json is valid JSON")
}

fn trust_from_json(value: &Value) -> TrustProxy {
    match value {
        Value::Bool(false) => TrustProxy::None,
        Value::Bool(true) => TrustProxy::All,
        Value::Number(n) => TrustProxy::Hops(n.as_u64().expect("hop count") as u32),
        Value::String(s) => TrustProxy::from_comma_separated(s),
        Value::Array(items) => TrustProxy::List(
            items
                .iter()
                .map(|v| v.as_str().expect("string entry").to_owned())
                .collect(),
        ),
        other => panic!("unexpected trust value {other}"),
    }
}

